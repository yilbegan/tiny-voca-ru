def plain_word(word: str) -> str:
    return word.replace("+", "").lower()


def _parse_nouns() -> dict[str, NounEntry]:
    nouns: dict[str, NounEntry] = {}
    for line in _NOUNS.strip().splitlines():
        lemma, kind, *forms = line.split()
        if len(forms) < 12:
            many = forms[0] if forms else lemma + "ов"
            forms = (
                [lemma + e for e in ("", "а", "у", "", "ом", "е")]
                + [lemma + "ы", many]
                + [lemma + e for e in ("ам", "ы", "ами", "ах")]
            )
        nouns[plain_word(lemma)] = (
            kind[0],
            kind.endswith("a"),
            tuple(forms[:6]),
            tuple(forms[6:12]),
            forms[12] if len(forms) > 12 else forms[1],
        )
    for adjective, adj_forms in _ADJECTIVES.items():
        adj = adj_forms.split()
        for lemma in ("метр", "километр", "сантиметр"):
            gender, animate, sg, pl, _ = nouns[lemma]
            nouns[f"{adjective} {lemma}"] = (
                gender,
                animate,
                tuple(f"{a} {n}" for a, n in zip(adj[:6], sg, strict=False)),
                tuple(f"{a} {n}" for a, n in zip(adj[6:], pl, strict=False)),
                f"{adj[7]} {sg[1]}",
            )
    return nouns


STRESSED: dict[str, NounEntry] = _parse_nouns()
NOUNS: dict[str, NounEntry] = {
    lemma: (g, a, tuple(map(plain_word, sg)), tuple(map(plain_word, pl)), plain_word(few))
    for lemma, (g, a, sg, pl, few) in STRESSED.items()
}
