def _numeral_stress() -> dict[str, str]:
    """Numeral forms whose homograph or rare stress should be marked explicitly."""
    table: dict[str, str] = {
        "один": "од+ин",
        "сорок": "с+орок",
        "сорока": "сорок+а",
        "пятой": "п+ятой",
    }
    for n in (5, 6, 7, 8, 9, 10, 20, 30):  # пять+ю
        word = numbers.cardinal(n, "ins")
        table[word] = word[:-1] + "+ю"
    for n in (50, 60, 70, 80):  # пять+юдесятью
        word = numbers.cardinal(n, "ins")
        table[word] = word.replace("ю", "+ю", 1)
    for h in range(2, 10):  # двухс+от, пятист+ам
        for case, tail in (("gen", "с+от"), ("dat", "ст+ам"), ("ins", "ст+ами"), ("prep", "ст+ах")):
            unit = numbers.cardinal(h, case)
            table[unit + tail.replace("+", "")] = unit + tail
    for case in CASES:  # тридц+атое
        for gender, plural in (("m", False), ("f", False), ("n", False), ("m", True)):
            for animate in (False, True):
                word = numbers.ordinal(30, case, gender, plural, animate)
                table[word] = word.replace("тридцат", "тридц+ат")
    return table


NUMERAL_STRESS: dict[str, str] = _numeral_stress()

